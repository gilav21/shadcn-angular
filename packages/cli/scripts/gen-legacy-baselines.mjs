// Regenerates `src/registry/legacy-baselines.ts` from git history.
//
// Mines every distinct historical blob of each legacy flat
// `packages/components/ui/<name>.component.ts`, canonicalizes it with the SAME
// projection the runtime uses (`canonicalize` from the built CLI), hashes it,
// and writes a sorted, deduped map `{ <name>: [sha256, ...] }`. `migrate` uses
// this to tell a pristine legacy install (safe to convert) from one the
// consumer customized (left untouched).
//
// Run from `packages/cli` AFTER `npm run build` (it imports the built
// `canonicalize`): `node scripts/gen-legacy-baselines.mjs`.
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { canonicalize } from '../dist/core/baseline.js';

const repoRoot = execFileSync('git', ['rev-parse', '--show-toplevel'], { encoding: 'utf-8' }).trim();
const git = (args) => execFileSync('git', ['-C', repoRoot, ...args], { encoding: 'utf-8', maxBuffer: 1 << 30 });

const UI = 'packages/components/ui';
const FLAT_RE = /^packages\/components\/ui\/[a-z][a-z0-9-]*\.component\.ts$/;

const paths = [...new Set(
  git(['log', '--all', '--name-only', '--pretty=format:', '--', `${UI}/*.component.ts`])
    .split('\n').map((s) => s.trim()).filter((p) => FLAT_RE.test(p)),
)];

const out = {};
for (const p of paths) {
  const name = p.slice(UI.length + 1, -'.component.ts'.length);
  const commits = git(['log', '--all', '--pretty=format:%H', '--', p]).split('\n').filter(Boolean);
  const hashes = new Set();
  for (const commit of commits) {
    let raw;
    try {
      raw = git(['show', `${commit}:${p}`]);
    } catch {
      continue; // path absent at this commit (rename boundary) — skip
    }
    hashes.add(createHash('sha256').update(canonicalize(raw, 'ui', '')).digest('hex'));
  }
  if (hashes.size) out[name] = [...hashes].sort((a, b) => a.localeCompare(b));
}

const sorted = Object.fromEntries(Object.entries(out).sort(([a], [b]) => a.localeCompare(b)));
const body = JSON.stringify(sorted, null, 2);
writeFileSync(
  new URL('../src/registry/legacy-baselines.ts', import.meta.url),
  '// GENERATED by scripts/gen-legacy-baselines.mjs — do not edit by hand.\n' +
  '// Canonical-form sha256 of every historical legacy flat <name>.component.ts,\n' +
  '// used to tell a pristine legacy install (safe to migrate) from one the\n' +
  '// consumer customized (left untouched).\n' +
  `export const LEGACY_BASELINES: Readonly<Record<string, readonly string[]>> = ${body} as const;\n`,
);

const total = Object.values(sorted).reduce((n, a) => n + a.length, 0);
console.log(`Wrote ${Object.keys(sorted).length} components, ${total} hashes to src/registry/legacy-baselines.ts`);
