// Regenerates `src/registry/component-baselines.ts` from git history.
//
// Mines every distinct historical blob of every component source file under
// `packages/components/ui/**` (`.ts`/`.html`/`.css`, excluding co-located
// `*.spec.ts` / `*.stories.ts`), canonicalizes it with the SAME projection the
// runtime uses (`canonicalize` — neutralizes the selector prefix + lib alias,
// then LF/trim-normalizes), hashes it, and writes one sorted, deduped GLOBAL
// set of hashes.
//
// Clean-reinstall uses this to tell a *pristine shadcn file the registry no
// longer ships* (a stale artifact of a past layout — safe to prune) from a file
// the consumer created or edited (which matches no baseline — protected). A
// global content set (not keyed by path) is deliberate: a file relocated across
// a refactor keeps its content, so it is still recognized as pristine wherever
// it sits.
//
// Run from `packages/cli` AFTER `npm run build`:
//   node scripts/gen-component-baselines.mjs
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { canonicalizeComponentFile } from '../dist/core/baseline.js';

const repoRoot = execFileSync('git', ['rev-parse', '--show-toplevel'], { encoding: 'utf-8' }).trim();
const git = (args) => execFileSync('git', ['-C', repoRoot, ...args], { encoding: 'utf-8', maxBuffer: 1 << 30 });

const UI = 'packages/components/ui';
const SRC_RE = /^packages\/components\/ui\/.+\.(ts|html|css)$/;
const isSource = (p) => SRC_RE.test(p) && !/\.(spec|stories)\.[tj]s$/.test(p);

const paths = [...new Set(
  git(['log', '--all', '--name-only', '--pretty=format:', '--', `${UI}/**`, `${UI}/*`])
    .split('\n').map((s) => s.trim()).filter(isSource),
)];

const hashes = new Set();
for (const p of paths) {
  const commits = git(['log', '--all', '--pretty=format:%H', '--', p]).split('\n').filter(Boolean);
  for (const commit of commits) {
    let raw;
    try {
      raw = git(['show', `${commit}:${p}`]);
    } catch {
      continue; // path absent at this commit (rename / creation boundary) — skip
    }
    try {
      hashes.add(createHash('sha256').update(canonicalizeComponentFile(raw, "ui", "")).digest('hex'));
    } catch {
      // canonicalize can't project this content (unexpected shape) — skip; an
      // unrecognized file is treated conservatively as customized at runtime.
    }
  }
}

const sorted = [...hashes].sort((a, b) => a.localeCompare(b));
const body = JSON.stringify(sorted, null, 2);
writeFileSync(
  new URL('../src/registry/component-baselines.ts', import.meta.url),
  '// GENERATED by scripts/gen-component-baselines.mjs — do not edit by hand.\n' +
  '// Canonical-form sha256 of every historical component source file under ui/,\n' +
  '// used by clean-reinstall to tell a pristine-but-superseded shadcn file (safe\n' +
  '// to prune) from a consumer-authored/edited one (protected).\n' +
  `export const COMPONENT_BASELINES: readonly string[] = ${body} as const;\n`,
);

console.log(`Wrote ${sorted.length} canonical hashes from ${paths.length} historical paths to src/registry/component-baselines.ts`);
