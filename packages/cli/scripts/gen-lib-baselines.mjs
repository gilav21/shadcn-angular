// Regenerates `src/registry/lib-baselines.ts` from git history.
//
// Mines every distinct historical blob of each installable shared lib file
// (`packages/components/lib/**/*.ts`, excluding `*.spec.ts`), plus the bundled
// `utils.ts` template, normalizes + hashes each with the SAME `hashContent` the
// runtime uses, and writes a sorted, deduped map `{ <libPath>: [sha256, ...] }`.
//
// Lib reconciliation uses this to tell a *pristine but stale* lib file (a past
// install that the registry has since moved past — safe to refresh) from one
// the consumer customized (e.g. a locale baked into `i18n/i18n.token.ts` by
// `set-locale` — must be protected). A file whose content matches no recorded
// baseline is treated conservatively as customized.
//
// Unlike component baselines, lib files are installed verbatim (no selector
// prefix / lib-alias rewrite), so the canonical projection is just
// `hashContent` (LF/trim-normalize + sha256) — no `canonicalize` needed.
//
// Run from `packages/cli` AFTER `npm run build`:
//   node scripts/gen-lib-baselines.mjs
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { hashContent } from '../dist/core/manifest.js';

const repoRoot = execFileSync('git', ['rev-parse', '--show-toplevel'], { encoding: 'utf-8' }).trim();
const git = (args) => execFileSync('git', ['-C', repoRoot, ...args], { encoding: 'utf-8', maxBuffer: 1 << 30 });

const LIB = 'packages/components/lib';
// Installable lib files only: runtime `.ts` under lib/, never the co-located
// `*.spec.ts` test files (consumers never receive those).
const LIB_RE = /^packages\/components\/lib\/.+\.ts$/;
const isInstallable = (p) => LIB_RE.test(p) && !p.endsWith('.spec.ts');

// (gitPath -> libKey): every installable lib file maps to its lib-relative key.
const sources = new Map();
const libPaths = [...new Set(
  git(['log', '--all', '--name-only', '--pretty=format:', '--', `${LIB}/**/*.ts`, `${LIB}/*.ts`])
    .split('\n').map((s) => s.trim()).filter(isInstallable),
)];
for (const p of libPaths) sources.set(p, p.slice(LIB.length + 1));

const out = {};
for (const [gitPath, libKey] of sources) {
  const commits = git(['log', '--all', '--pretty=format:%H', '--', gitPath]).split('\n').filter(Boolean);
  const hashes = new Set(out[libKey] ?? []);
  for (const commit of commits) {
    let raw;
    try {
      raw = git(['show', `${commit}:${gitPath}`]);
    } catch {
      continue; // path absent at this commit (rename / creation boundary) — skip
    }
    hashes.add(hashContent(raw));
  }
  if (hashes.size) out[libKey] = [...hashes];
}

// `utils.ts` is special: a consumer's copy is written from the bundled CLI
// *template* (`packages/cli/src/templates/utils.ts`), not from `lib/utils.ts`,
// and the template stores the file inside a `const UTILS_TEMPLATE = \`…\`` string
// literal — so the raw blob hashes to the wrong value. Extract the unescaped
// template OUTPUT from each historical blob (that is what lands on disk) and
// hash THAT.
const TEMPLATE_PATH = 'packages/cli/src/templates/utils.ts';
const utilsHashes = new Set(out['utils.ts'] ?? []);
const templateCommits = git(['log', '--all', '--pretty=format:%H', '--', TEMPLATE_PATH]).split('\n').filter(Boolean);
for (const commit of templateCommits) {
  let blob;
  try {
    blob = git(['show', `${commit}:${TEMPLATE_PATH}`]);
  } catch {
    continue;
  }
  const m = /UTILS_TEMPLATE\s*=\s*`([\s\S]*?)`\s*;/.exec(blob);
  if (!m) continue; // unexpected template shape — skip conservatively
  const output = m[1].replace(/\\([`$\\])/g, '$1');
  utilsHashes.add(hashContent(output));
}
if (utilsHashes.size) out['utils.ts'] = [...utilsHashes];

const sorted = Object.fromEntries(
  Object.entries(out)
    .map(([k, v]) => [k, [...new Set(v)].sort((a, b) => a.localeCompare(b))])
    .sort(([a], [b]) => a.localeCompare(b)),
);
const body = JSON.stringify(sorted, null, 2);
writeFileSync(
  new URL('../src/registry/lib-baselines.ts', import.meta.url),
  '// GENERATED by scripts/gen-lib-baselines.mjs — do not edit by hand.\n' +
  '// Normalized-form sha256 of every historical installable shared lib file,\n' +
  '// used to tell a pristine-but-stale lib file (safe to refresh) from one the\n' +
  '// consumer customized (left untouched).\n' +
  `export const LIB_BASELINES: Readonly<Record<string, readonly string[]>> = ${body} as const;\n`,
);

const total = Object.values(sorted).reduce((n, a) => n + a.length, 0);
console.log(`Wrote ${Object.keys(sorted).length} lib files, ${total} hashes to src/registry/lib-baselines.ts`);
