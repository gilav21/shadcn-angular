import type { LocaleMeta } from '../../lib/i18n';

/**
 * Locale dictionary for `<ui-page-builder>`. Component names, categories,
 * input labels and CSS values come from the host's `ComponentMeta` and the
 * user's layout, so they are never translated here. The property inspector
 * has its own dictionary (`PROPERTY_EDITOR_LOCALES`).
 *
 * `itemsCount` carries `{count}`, `addComponent` carries `{name}` and
 * `exampleValue` carries `{value}`; translators may move them but must keep
 * them.
 */
export interface PageBuilderLocale extends LocaleMeta {
    /** Palette sidebar heading and its `aria-label`. */
    components: string;
    /** Palette tile "add" button `aria-label`. Interpolates `{name}`. */
    addComponent: string;
    /** Toolbar item counter. Interpolates `{count}`. */
    itemsCount: string;
    /** Simulation button label while a simulation is running. */
    stopSim: string;
    /** Simulation button label while idle. */
    liveDemo: string;
    /** Simulation button `title`. */
    toggleSimulationTitle: string;
    switchToEditTitle: string;
    switchToPreviewTitle: string;
    /** Mode button label while previewing. */
    edit: string;
    /** Mode button label while editing. */
    preview: string;
    clear: string;
    clearBoardTitle: string;
    import: string;
    importLayoutTitle: string;
    save: string;
    saveLayoutTitle: string;
    export: string;
    exportLayoutTitle: string;
    /** Canvas empty state. */
    emptyCanvas: string;
    /** `aria-label` of the hidden import file input. */
    importJsonLabel: string;
    /** Inspector heading while a widget is selected, and its `aria-label`. */
    properties: string;
    /** Inspector heading while nothing is selected. */
    gridSettings: string;
    layoutConfiguration: string;
    rowHeight: string;
    gapSize: string;
    squareCells: string;
    columnConfiguration: string;
    count: string;
    width: string;
    showBorders: string;
    borderRadius: string;
    itemPadding: string;
    /** Resets item padding to `0px`. */
    none: string;
    itemPaddingHint: string;
    tip: string;
    tipBody: string;
    /** Input placeholder showing a sample value. Interpolates `{value}`. */
    exampleValue: string;
    columnWidthPlaceholder: string;
    /** `alert` for a layout file without `grid` / `items`. */
    invalidLayout: string;
    /** `alert` for a layout file that is not valid JSON. */
    parseFailed: string;
}

