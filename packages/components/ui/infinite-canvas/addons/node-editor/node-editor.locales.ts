/**
 * Every word the editor says on its own.
 *
 * The addons were localised from the start; the base was not, so a graph in a
 * Hebrew or Japanese application still announced "Connection cancelled." to a
 * screen reader and explained a refused wire in English. Most of these strings
 * are never SEEN — they are announcements and hover hints — which is exactly
 * why they were missed, and exactly why they matter: they are the whole
 * interface for someone using the editor without sight.
 *
 * Placeholders are `{name}` and filled by `interpolate` from `lib/i18n`.
 */
import type { LocaleMeta } from '../../../../lib/i18n';

export interface NodeEditorLocale extends LocaleMeta {
  /** The word for an input port, used in announcements. */
  directionInput: string;
  directionOutput: string;
  stateConnected: string;
  stateNotConnected: string;
  /** Appended to a port's accessible name when it has a type. */
  portTypeSuffix: string;
  /** `{label}, {direction}{type}, {state}` — a port's accessible name. */
  portAria: string;
  /** Hover text for an input port. */
  hintExpects: string;
  /** Hover text for an output port. */
  hintProvides: string;

  nodeAdded: string;
  connectionCancelled: string;
  connectionRemoved: string;
  nodesSelected: string;
  portFocused: string;
  connecting: string;
  nodeMoved: string;
  cannotConnect: string;
  connectionMade: string;
  removedSummary: string;

  rejectUnknownNode: string;
  rejectUnknownPort: string;
  rejectSameNode: string;
  rejectSameDirection: string;
  rejectPortDisabled: string;
  rejectTypeMismatch: string;
  rejectDuplicate: string;
  rejectOccupied: string;
  rejectCycle: string;
  /**
   * Why two ports would not join, named by ROLE rather than by which end the
   * drag started from.
   *
   * Dragging out of an input and dropping on an output produced "Style is an
   * object, Text expects text" — true, and backwards to read, because the port
   * doing the expecting was named second. The input expects; the output
   * provides; which one the hand moved first is not part of the explanation.
   */
  typeMismatchDetail: string;

  problemCycle: string;
  problemRequiredInput: string;
}

