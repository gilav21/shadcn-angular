import type { LocaleMeta } from '../../../../lib/i18n';

export interface NodeEditorHistoryLocale extends LocaleMeta {
  /** Heading for the panel. */
  heading: string;
  /** Shown before anything has run. */
  empty: string;
  /** Discards every kept run. */
  clear: string;
  /** Title of the detail panel — `{id}` is the run number. */
  run: string;
  /** Accessible name of a row: `{id}`, `{time}`, `{duration}`, `{count}`. */
  runLabel: string;
  /** Shows this run's values in the editor. */
  replay: string;
  /** Returns the editor to the present. */
  stopReplay: string;
  /** Hands the run over as a JSON document. */
  exportJson: string;
  /** `{node}` took `{duration}` — the slowest node of the run. */
  slowest: string;
  /** Column heading. */
  node: string;
  status: string;
  inputs: string;
  outputs: string;
  took: string;
  /** Status words, in the past tense — a run has already happened. */
  succeeded: string;
  failed: string;
  cancelled: string;
  /** Accessible name for the button that reveals a node. */
  reveal: string;
  /** Table caption for screen readers — `{id}` is the run number. */
  tableCaption: string;
}

